create table if not exists public.site_content (
  key        text primary key,
  data       jsonb       not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.site_content enable row level security;

drop policy if exists "ai_cung_doc_noi_dung" on public.site_content;
create policy "ai_cung_doc_noi_dung" on public.site_content
  for select to anon, authenticated using (true);

drop policy if exists "quan_tri_ghi_noi_dung" on public.site_content;
create policy "quan_tri_ghi_noi_dung" on public.site_content
  for all to authenticated using (true) with check (true);

-- ---------------------------------------------------------------------
-- 3. Kho ảnh (Storage)
--    Tạo bucket 'gallery' công khai; chỉ người đăng nhập được tải ảnh lên.
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('gallery','gallery',true)
on conflict (id) do update set public = true;

drop policy if exists "ai_cung_xem_anh" on storage.objects;
create policy "ai_cung_xem_anh" on storage.objects
  for select to anon, authenticated using (bucket_id = 'gallery');

drop policy if exists "quan_tri_tai_anh_len" on storage.objects;
create policy "quan_tri_tai_anh_len" on storage.objects
  for insert to authenticated with check (bucket_id = 'gallery');

drop policy if exists "quan_tri_ghi_de_anh" on storage.objects;
create policy "quan_tri_ghi_de_anh" on storage.objects
  for update to authenticated using (bucket_id = 'gallery');

drop policy if exists "quan_tri_xoa_anh" on storage.objects;
create policy "quan_tri_xoa_anh" on storage.objects
  for delete to authenticated using (bucket_id = 'gallery');

-- ---------------------------------------------------------------------
-- 4. Dọn dẹp định kỳ (tuỳ chọn)
--    Chỉ giữ số liệu 400 ngày gần nhất. Gọi tay, hoặc hẹn giờ bằng pg_cron.
-- ---------------------------------------------------------------------
create or replace function public.don_so_lieu_cu() returns void
language sql security definer set search_path = public as $$
  delete from public.page_views where created_at < now() - interval '400 days';
$$;

